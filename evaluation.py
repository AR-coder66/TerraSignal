"""
TerraSignal - Evaluation & Baseline Comparison Module

This module provides an objective, reproducible comparison between:
1. The Exhaustive Constrained Optimizer (optimal knapsack solver)
2. A Greedy Heuristic Baseline (orders targets by value-per-resource density)

Both planners consume identical feasibility models, target scores, and resource budgets.
"""

from dataclasses import dataclass
from typing import List, Dict, Any, Optional, Tuple
from data import ObservationRequest
from decision_engine import (
    PlanningWeights,
    EvaluatedTarget,
    OptimizationResult,
    evaluate_feasibility,
    calculate_target_value,
    optimize_observation_plan,
)


@dataclass
class BaselinePlanResult:
    """
    Plan generated by the greedy heuristic baseline.
    """
    method_name: str
    selected_targets: List[EvaluatedTarget]
    deferred_targets: List[EvaluatedTarget]
    total_value_selected: float
    time_used_minutes: float
    storage_used_gb: float
    time_utilization_pct: float
    storage_utilization_pct: float
    ranking_criterion: str


@dataclass
class ComparisonReport:
    """
    Direct comparative analysis between the optimal decision engine and the greedy baseline.
    """
    optimal_plan: OptimizationResult
    baseline_plan: BaselinePlanResult
    value_difference: float
    value_lift_pct: float
    targets_count_diff: int
    time_util_diff_pct: float
    storage_util_diff_pct: float
    is_identical: bool
    summary: str

    def to_dict(self) -> Dict[str, Any]:
        return {
            "optimal_value": round(self.optimal_plan.total_value_selected, 4),
            "baseline_value": round(self.baseline_plan.total_value_selected, 4),
            "value_difference": round(self.value_difference, 4),
            "value_lift_pct": round(self.value_lift_pct, 2),
            "optimal_targets_count": len(self.optimal_plan.selected_targets),
            "baseline_targets_count": len(self.baseline_plan.selected_targets),
            "targets_count_diff": self.targets_count_diff,
            "optimal_time_used": round(self.optimal_plan.time_used_minutes, 2),
            "baseline_time_used": round(self.baseline_plan.time_used_minutes, 2),
            "optimal_storage_used": round(self.optimal_plan.storage_used_gb, 2),
            "baseline_storage_used": round(self.baseline_plan.storage_used_gb, 2),
            "is_identical": self.is_identical,
            "summary": self.summary,
        }


def run_greedy_baseline(
    requests: List[ObservationRequest],
    available_time_minutes: float,
    available_storage_gb: float,
    scenario_cloud_cover: float,
    weights: Optional[PlanningWeights] = None,
) -> BaselinePlanResult:
    """
    Greedy Planning Heuristic:
    1. Filters targets by cloud feasibility.
    2. Calculates target value using the identical normalized weights.
    3. Calculates composite resource footprint:
         resource_cost = (duration_minutes / max(time_budget, 1e-6)) + (storage_gb / max(storage_budget, 1e-6))
       and efficiency metric:
         efficiency = target_value / resource_cost
    4. Ranks feasible targets descending by efficiency (tie-break: higher urgency, then alphabetical ID).
    5. Sequentially adds targets to the schedule if both imaging time and storage fit.
    """
    if weights is None:
        weights = PlanningWeights()

    # Step 1 & 2: Feasibility and value calculation
    feasible_targets: List[EvaluatedTarget] = []
    for req in requests:
        is_feas, feas_score, inf_reason = evaluate_feasibility(req, scenario_cloud_cover)
        if is_feas:
            val = calculate_target_value(req, weights)
            feasible_targets.append(
                EvaluatedTarget(
                    request=req,
                    target_value=val,
                    is_feasible=True,
                    feasibility_score=feas_score,
                    infeasible_reason=None,
                )
            )

    # Step 3: Compute efficiency score
    t_budget = max(available_time_minutes, 1e-6)
    s_budget = max(available_storage_gb, 1e-6)

    def sort_key(t: EvaluatedTarget) -> Tuple[float, float, str]:
        # Normalized multi-resource cost
        norm_cost = (t.request.duration_minutes / t_budget) + (t.request.storage_gb / s_budget)
        eff = t.target_value / max(norm_cost, 1e-6)
        # Higher efficiency first, then urgency first, then alphabetical ID
        return (eff, t.request.urgency, -ord(t.request.target_id[0]) if t.request.target_id else 0)

    # Sort descending by efficiency and urgency
    ranked = sorted(feasible_targets, key=sort_key, reverse=True)

    # Step 4: Greedy packing
    selected: List[EvaluatedTarget] = []
    deferred: List[EvaluatedTarget] = []
    cur_time = 0.0
    cur_storage = 0.0

    for t in ranked:
        if (cur_time + t.request.duration_minutes <= available_time_minutes + 1e-9) and \
           (cur_storage + t.request.storage_gb <= available_storage_gb + 1e-9):
            selected.append(t)
            cur_time += t.request.duration_minutes
            cur_storage += t.request.storage_gb
        else:
            deferred.append(t)

    tot_val = sum(t.target_value for t in selected)
    time_util = (cur_time / available_time_minutes * 100.0) if available_time_minutes > 0 else 0.0
    storage_util = (cur_storage / available_storage_gb * 100.0) if available_storage_gb > 0 else 0.0

    return BaselinePlanResult(
        method_name="Greedy Efficiency Heuristic",
        selected_targets=selected,
        deferred_targets=deferred,
        total_value_selected=tot_val,
        time_used_minutes=cur_time,
        storage_used_gb=cur_storage,
        time_utilization_pct=time_util,
        storage_utilization_pct=storage_util,
        ranking_criterion="Value / Normalized Resource Cost (Urgency & Lexical Tie-Break)",
    )


def compare_plans(
    optimal_plan: OptimizationResult,
    baseline_plan: BaselinePlanResult,
) -> ComparisonReport:
    """
    Produce a rigorous comparative report between optimal and baseline plans.
    """
    diff_val = optimal_plan.total_value_selected - baseline_plan.total_value_selected
    # Because optimal searches full feasible space, diff_val should be >= -1e-6
    if baseline_plan.total_value_selected > 0:
        lift_pct = (diff_val / baseline_plan.total_value_selected) * 100.0
    else:
        lift_pct = 100.0 if optimal_plan.total_value_selected > 0 else 0.0

    diff_targets = len(optimal_plan.selected_targets) - len(baseline_plan.selected_targets)
    diff_time = optimal_plan.time_utilization_pct - baseline_plan.time_utilization_pct
    diff_storage = optimal_plan.storage_utilization_pct - baseline_plan.storage_utilization_pct

    opt_set = {t.request.target_id for t in optimal_plan.selected_targets}
    base_set = {t.request.target_id for t in baseline_plan.selected_targets}
    is_identical = (opt_set == base_set)

    if is_identical:
        summary = (
            "Both the exhaustive optimizer and the greedy baseline converged on the identical "
            f"target portfolio ({len(opt_set)} targets, score: {optimal_plan.total_value_selected:.2f}). "
            "For this resource budget, the greedy density heuristic successfully reached the global optimum."
        )
    else:
        summary = (
            f"The exhaustive optimizer delivered +{diff_val:.2f} additional target value "
            f"(+{lift_pct:.1f}% lift) over the greedy heuristic. While the greedy heuristic "
            "commits irrevocably to early high-density targets, the global optimizer explored "
            "synergistic multi-target combinations to maximize dual-resource budget utilization."
        )

    return ComparisonReport(
        optimal_plan=optimal_plan,
        baseline_plan=baseline_plan,
        value_difference=diff_val,
        value_lift_pct=lift_pct,
        targets_count_diff=diff_targets,
        time_util_diff_pct=diff_time,
        storage_util_diff_pct=diff_storage,
        is_identical=is_identical,
        summary=summary,
    )
